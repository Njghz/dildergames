/**
 * Общие константы heartbeat-системы.
 * Файл не импортирует серверные модули — безопасно для клиентских компонентов.
 */

/** Интервал heartbeat на клиенте (мс) */
export const HEARTBEAT_INTERVAL_MS = 30_000;

/**
 * Окно «онлайн» (мс): если heartbeat не приходил дольше этого времени,
 * посетитель/администратор считается неактивным.
 */
export const ONLINE_WINDOW_MS = 5 * 60 * 1000;
